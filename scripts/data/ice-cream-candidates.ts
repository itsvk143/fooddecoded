async function verifyCandidates() {
  console.log(`Auditing ${CANDIDATES_60.length} candidates against existing database...`);
  const client = new MongoClient(uri);
  await client.connect();
  const db = client.db();
  const existingBarcodes = new Set(await db.collection("products").distinct("barcode"));

  const candidateBarcodes = new Set();
  let duplicates = 0;
  for (const c of CANDIDATES_60) {
    if (existingBarcodes.has(c.barcode)) {
      console.error(`COLLISION with DB barcode: ${c.barcode} (${c.name})`);
      duplicates++;
    }
    if (candidateBarcodes.has(c.barcode)) {
      console.error(`DUPLICATE within candidates: ${c.barcode} (${c.name})`);
      duplicates++;
    }
    candidateBarcodes.add(c.barcode);
  }

  console.log(`Duplicate check finished. Total collisions: ${duplicates}`);
  console.log(`Unique candidate barcodes: ${candidateBarcodes.size} / 60`);
  await client.close();
}

