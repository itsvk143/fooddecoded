async function main() {
  const targetDir = path.join(process.cwd(), 'public', 'images', 'cold-drinks');
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  for (const cfg of configs) {
    const svgPath = path.join(targetDir, cfg.filename);
    const content = generateDrinkSvg(cfg);
    fs.writeFileSync(svgPath, content, 'utf-8');
    console.log(`Generated drink SVG: ${cfg.filename}`);
  }

  console.log(`Successfully generated ${configs.length} cold drink SVGs in ${targetDir}`);
}

main().catch(console.error);
