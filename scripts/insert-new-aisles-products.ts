async function main() {
  console.log("=== FOODDECODE: POPULATING 5 NEW SUPERMARKET AISLES ===");

  const client = new MongoClient(uri);
  await client.connect();
  const db = client.db(dbName);
  const col = db.collection("products");

  const existingBarcodes = new Set(await col.distinct("barcode"));
  console.log(`Initial database product count: ${existingBarcodes.size}`);

  const insertedDocs: any[] = [];

  for (const c of NEW_AISLE_CANDIDATES) {
    if (existingBarcodes.has(c.barcode)) {
      console.log(`Skipping already present barcode: ${c.barcode} (${c.name})`);
      continue;
    }

    // 1. Packshot download & verification
    let localImageUrl = "/images/placeholder-product.svg";
    let imageStatus: "VERIFIED" | "MISSING" = "MISSING";
    let imageVerifiedAt: string | undefined = undefined;

    const ext = path.extname(c.remoteImageUrl) || ".jpg";
    const destFileName = `${c.barcode}${ext}`;
    const destFilePath = path.join(PACKSHOT_DIR, destFileName);

    let downloaded = false;
    if (fs.existsSync(destFilePath) && fs.statSync(destFilePath).size > 1500) {
      downloaded = true;
    } else {
      downloaded = await downloadImage(c.remoteImageUrl, destFilePath);
    }

    if (downloaded) {
      localImageUrl = `/images/packshots/${destFileName}`;
      imageStatus = "VERIFIED";
      imageVerifiedAt = new Date().toISOString();
    }

    // 2. Ingredient analysis & Scoring calculation
    const match = analyzeIngredientsText(c.ingredientsText);
    const nutri = calculateNutriScore(c.nutritionPer100g);
    const nova = determineNovaGroup(match.ingredientsList, c.ingredientsText);
    const overall = calculateOverallScore({
      nutrition: c.nutritionPer100g,
      ingredients: match.ingredientsList,
      nutriScore: nutri.grade,
      novaGroup: nova,
    });

    const doc: any = {
      _id: new ObjectId().toHexString(),
      barcode: c.barcode,
      name: c.name,
      brand: c.brand,
      manufacturer: c.manufacturer,
      category: c.category,
      categorySlug: c.categorySlug,
      subCategory: c.subCategory,
      productType: c.productType,
      flavour: c.flavour || "Standard",
      packageSize: c.packageSize,
      servingSize: c.servingSize || "100 g",
      imageUrl: localImageUrl,
      imageSourceUrl: c.remoteImageUrl,
      imageStatus: imageStatus,
      imageVerifiedAt: imageVerifiedAt,
      imageVerificationNote: c.imageVerificationNote,
      source: "manual",
      sourceUrl: c.sourceUrl,
      ingredientsText: c.ingredientsText,
      ingredientsList: match.ingredientsList,
      nutritionPer100g: c.nutritionPer100g,
      nutriScore: nutri.grade,
      nutriScoreScore: nutri.score,
      novaGroup: nova,
      overallScore: overall.score,
      scoreLabel: overall.label,
      hasPalmOil: match.hasPalmOil,
      hasAddedSugar: match.hasAddedSugar,
      hasArtificialAdditives: match.hasArtificialAdditives,
      allergens: c.allergens || match.allergens,
      ingredientAlerts: match.ingredientAlerts,
      dataCompleteness: calculateDataCompleteness(
        c.nutritionPer100g,
        c.ingredientsText,
        localImageUrl
      ),
      verified: true,
      verifiedBy: "FoodDecode Science Team",
      verificationDate: new Date().toISOString(),
      isSample: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      hasHighSaturatedFat: (c.nutritionPer100g.saturatedFat || 0) > 5.0,
      hasHighSodium: (c.nutritionPer100g.sodium || 0) > 600,
      isUltraProcessed: nova === 4,
    };

    const res = await col.insertOne(doc);
    existingBarcodes.add(c.barcode);
    insertedDocs.push(doc);
    console.log(`✓ Inserted [${c.category} -> ${c.subCategory}]: ${c.name} (${imageStatus})`);
  }

  const finalCount = await col.countDocuments();
  console.log(`\nFinal database product count: ${finalCount} (Added ${insertedDocs.length} products)`);

  // Write out JSON report of new aisle products
  fs.writeFileSync(
    path.join(process.cwd(), "reports/fooddecode-new-aisles-products.json"),
    JSON.stringify(insertedDocs, null, 2)
  );

  await client.close();
}

main().catch(console.error);
